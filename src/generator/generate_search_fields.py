"""
Generates a per-resource map of string-type search parameter names
from the FHIR search-parameters.json definition file.

Output: src/generated/searchFieldsByResource.ts (~4KB vs 1.6MB original)
"""
import json
import os

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
INPUT_PATH = os.path.join(SCRIPT_DIR, 'json', 'definitions.json', 'search-parameters.json')
OUTPUT_PATH = os.path.join(SCRIPT_DIR, '..', 'generated', 'searchFieldsByResource.ts')


def main():
    with open(INPUT_PATH, 'r') as f:
        data = json.load(f)

    resource_map: dict[str, list[str]] = {}

    for entry in data['entry']:
        resource = entry['resource']
        if resource['type'] != 'string':
            continue
        name = resource['name']
        for base in resource['base']:
            if base not in resource_map:
                resource_map[base] = []
            resource_map[base].append(name)

    # Sort for deterministic output
    for key in resource_map:
        resource_map[key].sort()

    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)

    with open(OUTPUT_PATH, 'w') as f:
        f.write('// Auto-generated by generate_search_fields.py — do not edit manually\n')
        f.write('const searchFieldsByResource: Record<string, string[]> = ')
        f.write(json.dumps(resource_map, indent=2, sort_keys=True))
        f.write(';\n\nexport default searchFieldsByResource;\n')

    entry_count = sum(len(v) for v in resource_map.values())
    print(f'Generated {OUTPUT_PATH}')
    print(f'  {len(resource_map)} resources, {entry_count} field entries')


if __name__ == '__main__':
    main()
